type Image = {
  width: number;
  height: number;
  pixels: Buffer;
};

function parseP6(ppm: Buffer): Image {
  if (ppm.length < 3 || ppm[0] !== 0x50 || ppm[1] !== 0x36) {
    throw new Error("Снимок экрана не PPM P6");
  }
  let offset = 2;
  const tokens: string[] = [];
  while (tokens.length < 3) {
    while (offset < ppm.length && ppm[offset] !== undefined && ppm[offset]! <= 0x20) {
      offset++;
    }
    if (offset >= ppm.length) {
      throw new Error("Обрезанный заголовок PPM");
    }
    if (ppm[offset] === 0x23) {
      while (offset < ppm.length && ppm[offset] !== 0x0a) {
        offset++;
      }
      continue;
    }
    const start = offset;
    while (offset < ppm.length && ppm[offset]! > 0x20) {
      offset++;
    }
    tokens.push(ppm.subarray(start, offset).toString("ascii"));
  }
  if (offset < ppm.length && ppm[offset]! <= 0x20) {
    offset++;
  }
  const width = Number(tokens[0]);
  const height = Number(tokens[1]);
  const maxval = Number(tokens[2]);
  if (!Number.isInteger(width) || !Number.isInteger(height) || maxval !== 255) {
    throw new Error(`Неожиданный PPM ${tokens.join(" ")}`);
  }
  const need = width * height * 3;
  const pixels = ppm.subarray(offset, offset + need);
  if (pixels.length !== need) {
    throw new Error("В PPM не хватает пикселей");
  }
  return { width, height, pixels };
}

function glyphAt(image: Image, col: number, row = 0): number[] {
  const rows: number[] = [];
  for (let y = 0; y < CELL_H; y++) {
    let bits = 0;
    const yy = row * CELL_H + y;
    for (let x = 0; x < 8; x++) {
      const pixel = ((yy * image.width) + (col * CELL_W + x)) * 3;
      if (image.pixels[pixel]! > 128) {
        bits |= 1 << (7 - x);
      }
    }
    rows.push(bits);
  }
  return rows;
}

function sameGlyph(actual: readonly number[], expected: readonly number[]): boolean {
  for (let row = 0; row < CELL_H; row++) {
    if (actual[row] !== expected[row]) {
      return false;
    }
  }
  return true;
}

/** null when VGA text row `row` shows `text`. */
export function screenTextError(ppm: Buffer, text: string, row = 0): string | null {
  const image = parseP6(ppm);
  if (image.width !== SCREEN_W || image.height !== SCREEN_H) {
    return `ожидался кадр VGA ${SCREEN_W}x${SCREEN_H}, получен ${image.width}x${image.height}`;
  }
  if (row < 0 || row >= 25) {
    return "строка вне экрана";
  }
  if (text.length > 80) {
    return "строка длиннее 80 столбцов";
  }
  for (let index = 0; index < text.length; index++) {
    const ch = text[index]!;
    const expected = GLYPHS[ch];
    if (expected == null) {
      return `нет эталона глифа для «${ch}»`;
    }
    const actual = glyphAt(image, index, row);
    if (!sameGlyph(actual, expected)) {
      return `на экране нет «${text}»: столбец ${index} («${ch}») не совпал`;
    }
  }
  return null;
}

/** True when `ch` is drawn in any text cell. */
export function screenShowsChar(ppm: Buffer, ch: string): boolean {
  const expected = GLYPHS[ch];
  if (expected == null) {
    return false;
  }
  const image = parseP6(ppm);
  if (image.width !== SCREEN_W || image.height !== SCREEN_H) {
    return false;
  }
  for (let row = 0; row < 25; row++) {
    for (let col = 0; col < 80; col++) {
      if (sameGlyph(glyphAt(image, col, row), expected)) {
        return true;
      }
    }
  }
  return false;
}

/** Paint `text` with the same cell layout QEMU uses, for the decoder test. */
export function paintTextPpm(text: string): Buffer {
  const pixels = Buffer.alloc(SCREEN_W * SCREEN_H * 3);
  for (let index = 0; index < text.length; index++) {
    const glyph = GLYPHS[text[index]!];
    if (glyph == null) {
      throw new Error(`нет глифа «${text[index]}»`);
    }
    for (let y = 0; y < CELL_H; y++) {
      for (let x = 0; x < 8; x++) {
        if ((glyph[y]! & (1 << (7 - x))) === 0) {
          continue;
        }
        const pixel = ((y * SCREEN_W) + (index * CELL_W + x)) * 3;
        pixels[pixel] = 255;
        pixels[pixel + 1] = 255;
        pixels[pixel + 2] = 255;
      }
    }
  }
  return Buffer.concat([
    Buffer.from(`P6\n${SCREEN_W} ${SCREEN_H}\n255\n`),
    pixels,
  ]);
}
